/** 根据 Modrinth 项目返回中文名；没有对照时返回空字符串。 */
export function zhModName(project) {
  if (!project) return '';
  const key = String(project.slug || project.project_id || project.id || '').toLowerCase();
  return ZH[key] || '';
}

/** 界面显示名：优先中文名，没有则用原名。 */
export function modDisplayName(project) {
  return zhModName(project) || project?.title || project?.slug || '未知模组';
}

export function hasZhName(project) {
  return !!zhModName(project);
}
